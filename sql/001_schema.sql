-- Ask My Notes: database schema
-- Run once in the Supabase SQL Editor of a new, empty project.

create extension if not exists vector;

create table notes (
  id bigint generated by default as identity primary key,
  title text not null,
  raw_content text not null,
  language text not null default 'en' check (language in ('en', 'xh', 'mixed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table notes_chunks (
  id bigint generated by default as identity primary key,
  note_id bigint not null references notes(id) on delete cascade,
  content text not null,
  language text not null default 'en' check (language in ('en', 'xh', 'mixed')),
  embedding vector(768),
  created_at timestamptz not null default now()
);

create index notes_chunks_note_id_idx on notes_chunks(note_id);
create index notes_chunks_embedding_idx on notes_chunks using hnsw (embedding vector_cosine_ops);

-- Reconstructed from how server code calls it: rpc('match_notes', { query_embedding, match_count })
create function match_notes(
  query_embedding vector(768),
  match_count int
)
returns table (
  id bigint,
  note_id bigint,
  title text,
  content text,
  language text,
  similarity double precision
)
language sql stable
as $$
  select
    c.id,
    c.note_id,
    n.title,
    c.content,
    c.language,
    1 - (c.embedding <=> query_embedding) as similarity
  from notes_chunks c
  join notes n on n.id = c.note_id
  where c.embedding is not null
  order by c.embedding <=> query_embedding
  limit match_count;
$$;

-- The server uses the secret key, which bypasses row level security.
-- With RLS on and no policies, the public key can read nothing.
alter table notes enable row level security;
alter table notes_chunks enable row level security;